-- Employee records. "id" is the internal surrogate key; "employee_code" is the
-- Employee ID shown to administrators.
CREATE TABLE employees (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code  VARCHAR(20)    NOT NULL,
    full_name      VARCHAR(100)   NOT NULL,
    email          VARCHAR(150)   NOT NULL,
    phone          VARCHAR(20)    NOT NULL,
    department     VARCHAR(60)    NOT NULL,
    designation    VARCHAR(80)    NOT NULL,
    joining_date   DATE           NOT NULL,
    salary         NUMERIC(12, 2) NOT NULL,
    status         VARCHAR(10)    NOT NULL,
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT uk_employees_employee_code UNIQUE (employee_code),
    CONSTRAINT uk_employees_email UNIQUE (email),
    -- The application stores emails in lower case; this guards against any
    -- write path that skips normalisation and would allow case-variant duplicates.
    CONSTRAINT ck_employees_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_employees_salary_non_negative CHECK (salary >= 0),
    CONSTRAINT ck_employees_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- Supports the department and status filters on the employee list.
CREATE INDEX idx_employees_department ON employees (department);
CREATE INDEX idx_employees_status ON employees (status);
